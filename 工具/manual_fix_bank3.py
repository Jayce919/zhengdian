def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--apply", action="store_true")
    args = ap.parse_args()

    path = SRC / F
    data = json.loads(path.read_text("utf-8"))
    by_id = {q["id"]: q for q in data}

    for qid, field, old, new in EDITS:
        q = by_id[qid]
        if field == "options":
            hit = False
            for i, o in enumerate(q["options"]):
                if o == old:
                    q["options"][i] = new
                    hit = True
                    break
            if not hit:
                raise SystemExit(f"未命中选项 {qid}: {old[:30]}")
            continue
        if old not in q[field]:
            raise SystemExit(f"未命中 {qid}.{field}: {old[:30]}")
        q[field] = q[field].replace(old, new, 1)

    # 兜底：去掉题干末尾残留的半括号
    stripped = 0
    for q in data:
        s = q["stem"].rstrip()
        if s.endswith(("(", "（")):
            q["stem"] = s[:-1].rstrip()
            stripped += 1

    print(f"命中 {len(EDITS)} 处，另清理末尾半括号 {stripped} 处")
    if not args.apply:
        print("（试运行，加 --apply 写盘）")
        return

    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    backup = BACKUP / f"知识点-人工校订3-{stamp}"
    backup.mkdir(parents=True, exist_ok=True)
    shutil.copy2(path, backup / path.name)
    path.write_text(json.dumps(data, ensure_ascii=False, indent=1) + "\n", encoding="utf-8")
    print("已备份到", backup)


if __name__ == "__main__":
    main()
