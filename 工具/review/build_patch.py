def main():
    items = json.load(open(SRC, encoding="utf-8"))
    by_id = {x["id"]: x for x in items}
    sel = [x for x in items if x["subject"] in ("maozhongte", "sifa")]
    sel_ids = {x["id"] for x in sel}

    fixes, deletes, errors = [], [], []
    stats = {"stem": 0, "explain": 0}

    for qid, (new_stem, new_explain, reason) in R.items():
        if qid not in by_id:
            errors.append("missing id: " + qid)
            continue
        x = by_id[qid]
        if qid not in sel_ids:
            errors.append("out of scope: " + qid)
            continue

        if new_stem is not None:
            if x["answer"] is not False:
                errors.append("answer not false: " + qid)
            if len(new_stem) > 60:
                errors.append("stem too long (%d): %s" % (len(new_stem), qid))
            if "前者" in new_stem or "后者" in new_stem:
                errors.append("pronoun in stem: " + qid)
            if not new_stem.endswith("。"):
                errors.append("stem no period: " + qid)
            if len(re.findall(r"[。！？]", new_stem)) != 1:
                errors.append("stem not single sentence: " + qid)
            if new_stem == x["stem"]:
                errors.append("stem unchanged: " + qid)
            fixes.append({
                "file": "questions_panduan.json",
                "id": qid,
                "field": "stem",
                "old": x["stem"],
                "new": new_stem,
                "reason": reason,
            })
            stats["stem"] += 1

        if new_explain is not None and new_explain != x["explain"]:
            if "前者" in new_explain or "后者" in new_explain:
                errors.append("pronoun in explain: " + qid)
            if "正确表述" not in new_explain:
                errors.append("explain lacks 正确表述: " + qid)
            fixes.append({
                "file": "questions_panduan.json",
                "id": qid,
                "field": "explain",
                "old": x["explain"],
                "new": new_explain,
                "reason": reason,
            })
            stats["explain"] += 1

    # 校验 old 精确存在且唯一
    for f in fixes:
        x = by_id[f["id"]]
        if f["old"] != x[f["field"]]:
            errors.append("old mismatch: %s/%s" % (f["id"], f["field"]))

    # 统计：覆盖到的假判断题数、仍未改写的“是一回事”
    cj = [x for x in sel if x["id"].startswith("q-cj-")]
    rewritten = [x for x in cj if x["id"] in R and R[x["id"]][0] is not None]
    left = [x["id"] for x in cj if x["id"] not in R]
    no_yihuish = [x["id"] for x in sel if "是一回事" in x["stem"] and x["id"] not in R]

    out = {"fixes": fixes, "deletes": deletes}
    with open(OUT, "w", encoding="utf-8") as fh:
        json.dump(out, fh, ensure_ascii=False, indent=2)

    print("fixes=%d (stem=%d, explain=%d), deletes=%d"
          % (len(fixes), stats["stem"], stats["explain"], len(deletes)))
