def main():
    data = json.load(open(SRC, encoding="utf-8"))
    by_id = {q["id"]: q for q in data if q.get("subject") == "mayuan"}
    fixes, errors = [], []

    for qid, new_stem, new_explain in REWRITES:
        q = by_id.get(qid)
        if not q:
            errors.append("missing id " + qid); continue
        if q["answer"] is not False:
            errors.append("answer not false " + qid); continue
        if not new_stem or not new_explain:
            errors.append("empty new " + qid); continue
        if len(new_stem) > 60:
            errors.append("too long %s %d" % (qid, len(new_stem))); continue
        if "前者" in new_stem or "后者" in new_stem:
            errors.append("deictic " + qid); continue
        if "是一回事" in new_stem or "一回事" in new_stem:
            errors.append("vague " + qid); continue
        fixes.append({"file": "questions_panduan.json", "id": qid, "field": "stem",
                      "old": q["stem"], "new": new_stem, "reason": "改写模糊表述"})
        fixes.append({"file": "questions_panduan.json", "id": qid, "field": "explain",
                      "old": q["explain"], "new": new_explain, "reason": "解析随题干同步改写"})

    for qid, field, old, new, reason in SMALL:
        q = by_id.get(qid)
        if not q:
            errors.append("missing id " + qid); continue
        if old not in q[field]:
            errors.append("old not found %s %s" % (qid, field)); continue
        if not new:
            errors.append("empty new " + qid); continue
        fixes.append({"file": "questions_panduan.json", "id": qid, "field": field,
                      "old": old, "new": new, "reason": reason})

    # 应用后检查新题干唯一
    stems = {q["id"]: q["stem"] for q in by_id.values()}
    for f in fixes:
        if f["field"] == "stem":
            stems[f["id"]] = stems[f["id"]].replace(f["old"], f["new"], 1)
    vals = list(stems.values())
    if len(vals) != len(set(vals)):
        seen = set()
        for qid, s in stems.items():
            if s in seen: errors.append("duplicate stem " + qid)
            seen.add(s)

    if errors:
        print("ERRORS:", len(errors))
        for e in errors: print(" -", e)
        sys.exit(1)

    out = {"fixes": fixes, "deletes": []}
    json.dump(out, open(OUT, "w", encoding="utf-8"), ensure_ascii=False, indent=2)
    print("rewrites:", len(REWRITES), "small fixes:", len(SMALL),
          "total fixes:", len(fixes), "deletes: 0")

if __name__ == "__main__":
    main()
