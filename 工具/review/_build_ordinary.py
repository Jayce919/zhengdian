def main():
    data = {}
    for name in ("questions.json", "questions_mcq.json", "questions_mcq2.json", "questions_hats.json"):
        data[name] = json.loads((SRC / name).read_text(encoding="utf-8"))
    index = {(name, q["id"]): q for name, qs in data.items() for q in qs}

    fixes = []
    errors = []

    # hats explains
    for qid, new in HAT_EXPLAINS.items():
        q = index.get(("questions_hats.json", qid))
        if not q:
            errors.append(f"missing {qid}")
            continue
        old = q.get("explain", "")
        fixes.append({"file": "questions_hats.json", "id": qid, "field": "explain",
                      "old": old, "new": new,
                      "reason": "原解析仅有“标准答案”，未说明理由；补写为30–100字，点明概念内涵及易混点。"})

    # hats stems
    for qid, new in STEM_FIXES.items():
        q = index.get(("questions_hats.json", qid))
        if not q:
            errors.append(f"missing {qid}")
            continue
        fixes.append({"file": "questions_hats.json", "id": qid, "field": "stem",
                      "old": q["stem"], "new": new, "reason": STEM_REASONS[qid]})

    # hats options
    for qid, old_opt, new_opt, reason in OPTION_FIXES:
        q = index.get(("questions_hats.json", qid))
        if not q:
            errors.append(f"missing {qid}")
            continue
        if old_opt not in q["options"]:
            errors.append(f"option not found {qid}: {old_opt}")
            continue
        fixes.append({"file": "questions_hats.json", "id": qid, "field": "options",
                      "old": old_opt, "new": new_opt, "reason": reason})

    # other explains
    for (name, qid), new in OTHER_EXPLAIN_FIXES.items():
        q = index.get((name, qid))
        if not q:
            errors.append(f"missing {name}/{qid}")
            continue
        fixes.append({"file": name, "id": qid, "field": "explain",
                      "old": q.get("explain", ""), "new": new,
                      "reason": "原解析过短或只复述答案，补写为30–100字，说明正确项依据并辨析易混项。"})

    # other stems
    for (name, qid), (old, new, reason) in OTHER_STEM_FIXES.items():
        q = index.get((name, qid))
        if not q:
            errors.append(f"missing {name}/{qid}")
            continue
        if q["stem"] != old:
            errors.append(f"stem mismatch {name}/{qid}")
            continue
        fixes.append({"file": name, "id": qid, "field": "stem",
                      "old": old, "new": new, "reason": reason})

    # self-check
    for f in fixes:
        q = index.get((f["file"], f["id"]))
        if not q:
            errors.append(f"bad id {f['file']}/{f['id']}")
            continue
        field = f["field"]
        if field == "options":
            if f["old"] not in q["options"]:
                errors.append(f"old not in options {f['id']}")
            if not f["new"]:
                errors.append(f"empty new {f['id']}")
        else:
            text = q.get(field, "")
            if not isinstance(text, str):
                errors.append(f"field type {f['id']}.{field}")
            elif f["old"] not in text:
                errors.append(f"old not found {f['id']}.{field}: {f['old'][:30]}")
            if not f["new"]:
                errors.append(f"empty new {f['id']}.{field}")
        if field == "explain":
            n = len(f["new"])
            if not (30 <= n <= 100):
                errors.append(f"explain length {f['id']} = {n}")

    # deletes check
    for d in DELETES:
        if (d["file"], d["id"]) not in index:
            errors.append(f"delete id missing {d['file']}/{d['id']}")

    # no duplicate fix of same (file,id,field)
    seen = {}
    for f in fixes:
        k = (f["file"], f["id"], f["field"])
        if k in seen:
            errors.append(f"duplicate fix {k}")
        seen[k] = True

    out = {"fixes": fixes, "deletes": DELETES}
    OUT.write_text(json.dumps(out, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")

    print(f"fixes={len(fixes)} deletes={len(DELETES)} errors={len(errors)}")
    for e in errors:
        print("ERR", e)
    from collections import Counter
    print(Counter((f["file"], f["field"]) for f in fixes))


if __name__ == "__main__":
    main()
