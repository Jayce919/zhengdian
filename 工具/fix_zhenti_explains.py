# 清除页眉、水印、下一题残片、题号答案标记
CLEAN = [
    (re.compile(r"\s*\d{4}\s*年思想政治理论试题.*?（共\s*\d+\s*页）\s*"), ""),
    (re.compile(r"\s*\d{4}\s*年思想政治理论试题.*?页）\s*"), ""),
    (re.compile(r"\s*2022年考研政治真题解析共12页by：光速考研\s*#*\s*"), ""),
    (re.compile(r"\s*2023年考研政治真题及解析\s*"), ""),
    (re.compile(r"^\s*\d{1,2}\s*[.．、]\s*[\[【（(]?\s*(?:标准)?答案\s*[\]】）)]?\s*[A-D]{1,4}\s*"), ""),
    (re.compile(r"\s*\d{0,2}\s*[-—&]?\s*[\[【（(]\s*(?:标准)?答案\s*[\]】）)]\s*[A-D]{1,4}.*$"), ""),
    (re.compile(r"^\s*【光速考研考点点拨】[^【]*?(?=本|中|党|人|社|文|历|马|毛|邓|新)"), ""),
    (re.compile(r"^\s*【解析】\s*"), ""),
]


def main():
    apply = "--apply" in sys.argv
    bank = json.loads(BANK.read_text(encoding="utf-8"))
    by_id = {q["id"]: q for q in bank}
    errors, changed = [], 0

    for qid, text in REPLACE.items():
        q = by_id.get(qid)
        if not q:
            errors.append(f"{qid}: 题目不存在")
            continue
        if q["explain"].strip() == text.strip():
            continue
        q["explain"] = text
        changed += 1

    for q in bank:
        old = q["explain"]
        new = old
        for pat, repl in CLEAN:
            new = pat.sub(repl, new)
        new = re.sub(r"\s{2,}", " ", new).strip()
        if new != old:
            q["explain"] = new
            changed += 1

    print(f"解析改动 {changed} 处")
    if errors:
        print("\n".join("✗ " + e for e in errors))
        sys.exit(1)
    if not apply:
        print("（试运行，未写盘；加 --apply 生效）")
        return

    BACKUP.mkdir(exist_ok=True)
    stamp = datetime.now().strftime("%Y%m%d-%H%M%S")
    dst = BACKUP / f"知识点-真题解析修复-{stamp}"
    dst.mkdir(parents=True)
    shutil.copy2(BANK, dst / BANK.name)
    BANK.write_text(json.dumps(bank, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print(f"已写盘；备份 → {dst}")


if __name__ == "__main__":
    main()
